"""Portable research-output index; omit local reruns, caches and absolute paths."""
from pathlib import Path
import hashlib,json

ROOT_FILES=('statistical_tests.csv','forecast_loss_differentials.csv','bootstrap_sensitivity.csv',
 'strategy_summary_v2.csv','performance_attribution.csv','economic_bootstrap.csv','drawdown_episode_analysis.csv',
 'horizon_comparison.csv','horizon_statistical_tests.csv','risk_matched_comparison.csv','exposure_calibration.csv',
 'extended_model_comparison.csv','extended_statistical_tests.csv','asymmetry_response.csv','chronological_validation.csv',
 'phase2_metadata.json','phase2_validation.json','phase2_reproducibility.csv','phase2_tests.txt',
 'RESEARCH_REPORT_V2.md','RESEARCH_REPORT.md')
FIGURES=('forecast_loss_comparison','exposure_comparison','turnover_cost_analysis','risk_matched_performance',
         'asymmetric_volatility_models','period_comparison')


def inventory(out=Path('outputs')):
    out=Path(out)
    files=[out/name for name in ROOT_FILES if (out/name).exists()]
    files+=list(out.glob('*_horizons.csv'))+list(out.glob('*_cash_alignment.csv'))
    for folder in ('phase2_models','review'):
        files += [p for p in (out/folder).rglob('*') if p.is_file() and not p.name.endswith('.log') and 'install' not in p.name]
    files += [out/'figures'/f'{name}.{ext}' for name in FIGURES for ext in ('png','pdf') if (out/'figures'/f'{name}.{ext}').exists()]
    files=sorted(set(files),key=str)
    records=[{'path':str(p.relative_to(out)),'bytes':p.stat().st_size,
              'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in files]
    (out/'phase2_artifacts.json').write_text(json.dumps(records,indent=2))
    lines=['# Research output index','',
        'Paths below are relative to this `outputs/` directory. Main portfolio deliverables:',
        '[final report](../FINAL_RESEARCH_REPORT.md), [one-page summary](../PROJECT_SUMMARY.md),',
        'and [full technical report](RESEARCH_REPORT_V2.md).','',
        'Detailed daily ledgers are generated by `python phase2.py` in `phase2_ledgers/`.',
        'They and duplicate reproduction runs are excluded from publication; scripts regenerate them.',
        'The frozen baseline is retained in `../archive/phase1/` for provenance and input verification.','',
        '| Relative path | Bytes |','| --- | --- |']
    lines += [f"| `{r['path']}` | {r['bytes']} |" for r in records]
    (out/'PHASE2_OUTPUTS.md').write_text('\n'.join(lines)+'\n')
    return len(records)
